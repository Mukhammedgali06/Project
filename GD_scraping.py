"""2. Data Cleaning and Utilities"""

import re

def clean_number(text):
    """
    Cleans a string containing numbers, handles commas, and converts to int.
    Used for Ratings_Count, Num_Reviews.
    """
    if text:
        # Remove non-digit and non-comma characters
        cleaned = re.sub(r'[^\d,]', '', text)
        return int(cleaned.replace(',', ''))
    return None

def clean_rating(text):
    """
    Extracts the floating-point rating from a string.
    Used for Avg_Rating.
    """
    if text:
        # Finds the pattern of one or more digits, a decimal point, and one or more digits
        match = re.search(r'(\d+\.\d+)', text)
        return float(match.group(1)) if match else None
    return None

"""3. Core Scraping Functions"""

def scrape_book_details(session, book_url):
    """Scrapes year, page count, and reviews from the individual book page."""
    # ULTRA-SAFE speed for individual book pages
    time.sleep(random.uniform(5, 10))
    details = {'Year': None, 'Num_Reviews': None, 'Num_Pages': None}

    try:
        book_response = session.get(book_url, headers=HEADERS, timeout=15)
        book_response.raise_for_status()
        book_soup = BeautifulSoup(book_response.text, 'html.parser')

        body_text = book_soup.get_text()

        # Extract Year from publicationInfo element
        date_element = book_soup.find('p', {'data-testid': 'publicationInfo'})
        if date_element:
            text = date_element.get_text(strip=True)
            year_match = re.search(r'(\d{4})', text)
            if year_match:
                details['Year'] = int(year_match.group(1))

        # Extract Pages using regex across the whole body text
        pages_match = re.search(r'(\d+)\s+(?:pages|page)', body_text, re.IGNORECASE)
        if pages_match:
            details['Num_Pages'] = int(pages_match.group(1))

        # Extract Reviews using regex across the whole body text
        reviews_match = re.search(r'([\d,]+)\s+reviews', body_text, re.IGNORECASE)
        if reviews_match:
            details['Num_Reviews'] = clean_number(reviews_match.group(1))

    except Exception as e:
        # Pass silently on error, details will remain None
        pass

    return details

def scrape_goodreads_data():
    """Main function to scrape a batch of list pages."""
    global RESUME_START_PAGE

    start_page = RESUME_START_PAGE
    end_page_for_batch = min(start_page + PAGES_PER_BATCH, FINAL_TARGET_PAGE + 1)

    print(f"Starting Goodreads BATCH scraping. Range: Pages {start_page} to {end_page_for_batch - 1}...")

    all_data = []
    session = requests.Session()
    session.headers.update(HEADERS)

    initial_id_count = (RESUME_START_PAGE - 1) * 100

    for page in range(start_page, end_page_for_batch):
        url = f"{BASE_URL}?page={page}{REF_PARAM}"
        print(f"Scraping List Page {page}/{FINAL_TARGET_PAGE}")

        try:
            response = session.get(url, timeout=20)
            response.raise_for_status()
            soup = BeautifulSoup(response.text, 'html.parser')
            item_rows = soup.find_all('tr', itemscope=True, itemtype='http://schema.org/Book')

            if not item_rows:
                print("No items found on this page. Stopping early.")
                break

            for row in item_rows:
                book_data = {}
                book_url = None

                try:
                    # 1. Scrape data from the List Page
                    title_tag = row.find('a', class_='bookTitle')
                    book_data['Title'] = title_tag.find('span', itemprop='name').get_text(strip=True) if title_tag else 'N/A'
                    book_url = f"https://www.goodreads.com{title_tag['href']}"

                    author_tag = row.find('a', class_='authorName')
                    book_data['Author'] = author_tag.get_text(strip=True) if author_tag else 'N/A'

                    rating_container = row.find('span', class_='minirating')
                    rating_text = rating_container.get_text(strip=True) if rating_container else ''
                    book_data['Avg_Rating'] = clean_rating(rating_text)

                    ratings_count_match = re.search(r'—\s([\d,]+)\sratings', rating_text)
                    book_data['Ratings_Count'] = clean_number(ratings_count_match.group(1)) if ratings_count_match else None

                    book_data['URL'] = book_url

                    # 2. Scrape data from the Detail Page (nested call)
                    details = scrape_book_details(session, book_url)
                    book_data['Number of Reviews'] = details['Num_Reviews']
                    book_data['Year'] = details['Year']
                    book_data['Number of Pages'] = details['Num_Pages']

                    book_data['ID'] = initial_id_count + len(all_data) + 1
                    all_data.append(book_data)

                except Exception as e:
                    continue

            print(f"Items scraped from page: {len(item_rows)}. Total scraped in this run: {len(all_data):,}")

        except requests.exceptions.RequestException as e:
            print(f"CRITICAL ERROR fetching page {page}: {e}")
            break

        # Safety delay between list pages
        sleep_time = random.uniform(10, 15)
        print(f"Pausing for {sleep_time:.2f} seconds...")
        time.sleep(sleep_time)

    return pd.DataFrame(all_data), page + 1

