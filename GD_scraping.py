def create_csv_file(df_new):
    """
    Creates or appends to the final CSV file, handling file existence and data types.
    Uses sep=';' and decimal=',' for Excel compatibility.
    """
    filename = FINAL_FILENAME
    df_final = pd.DataFrame()

    try:
        # 1. Load existing data
        df_existing = pd.read_csv(FINAL_FILENAME, sep=';', decimal=',')

        # Type casting for safer concatenation
        for col in ['Year', 'Number of Reviews', 'Number of Pages']:
            df_existing[col] = df_existing[col].astype('Int64', errors='ignore')

        # 2. Combine old and new data
        df_final = pd.concat([df_existing, df_new], ignore_index=True)
        # 3. Recalculate ID for the combined file
        df_final['ID'] = range(1, len(df_final) + 1)

        print(f"Appended {len(df_new):,} new records to the existing file.")

    except FileNotFoundError:
        df_final = df_new
        print("Created new file (no existing data found for append).")

    # Final formatting and column order
    df_final['Year'] = df_final['Year'].astype('Int64', errors='ignore')

    FINAL_COLUMNS = [
        'ID', 'Title', 'Author', 'Avg_Rating', 'Ratings_Count',
        'Number of Reviews', 'Year', 'Number of Pages', 'URL'
    ]

    df_final = df_final[FINAL_COLUMNS]

    # Save the file (using ; and , for Excel compatibility)
    df_final.to_csv(FINAL_FILENAME, index=False, encoding='utf-8-sig', sep=';', decimal=',')

    print(f"\nCSV File Updated/Created: {FINAL_FILENAME}")
    print(f"Total Records in FINAL file: {len(df_final):,}")

    return df_final


